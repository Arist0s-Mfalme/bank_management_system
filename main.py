# 1 Creating a bank account


def create_account():
    # Accept customer details

    first_name = input("Enter your first name : ")
    last_name = input("Enter your last name : ")
    phone = input("Enter Phone Number : ")
    address = input("Enter Address : ")
    account_no = int(input("Enter Account Number : "))
    account_type = input("Enter Account Type (Saving/Current) : ")
    balance = float(input("Enter Opening Balance : "))

    # Check whether the account already exists
    qry = "SELECT * FROM Accounts WHERE account_no=%s"
    mycur.execute(qry, (account_no,))
    result = mycur.fetchone()

    # Insert account details
    if result is None:
        sql_customers = """
        INSERT INTO Customers(first_name, last_name, phone, address)
        VALUES(%s, %s, %s, %s)
        """

        values_customers = (first_name, last_name, phone, address)
        mycur.execute(sql_customers, values_customers)
        mycon.commit()

        # Grab the hidden auto-incremented ID generated by mysql
        generated_customer_id = mycur.lastrowid

        sql_account = """
        INSERT INTO Accounts(account_no, customer_id, account_type, balance)
        VALUES(%s,%s,%s,%s)
        """

        values_account = (account_no, generated_customer_id,
                          account_type, balance)
        mycur.execute(sql_account, values_account)
        mycon.commit()

        # Display the result
        print("\nAccount Created Successfully.")
    else:
        print("\nAccount Number Already Exists.")


create_account()
